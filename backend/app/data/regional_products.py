def get_regional_products_for_country(country: str) -> List[EvidenceObject]:
    """Retrieve catalog products matching or compatible with the target country."""
    c_lower = country.strip().lower() if country else "global"
    if c_lower in ("global", "all"):
        return REGIONAL_PRODUCTS

    matched: List[EvidenceObject] = []
    country_aliases = {
        "sri lanka": ["sri lanka", "sri-lanka", "lk", "en:sri-lanka"],
        "united kingdom": ["united kingdom", "united-kingdom", "uk", "great britain", "gb", "en:united-kingdom"],
        "united states": ["united states", "united-states", "us", "usa", "en:united-states"],
        "india": ["india", "in", "en:india"],
        "australia": ["australia", "au", "en:australia"],
        "canada": ["canada", "ca", "en:canada"],
    }
    targets = country_aliases.get(c_lower, [c_lower])

    for p in REGIONAL_PRODUCTS:
        p_countries = [c.lower() for c in p.countries]
        if any(t in c or c in t for c in p_countries for t in targets):
            matched.append(p)

    return matched
